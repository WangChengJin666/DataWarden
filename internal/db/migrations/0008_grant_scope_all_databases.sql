-- 授权范围提升到「整个数据源」：申请不再需要选库
--
-- 产品口径变化：申请授权时只需要选数据源，审批通过即拥有该数据源下
-- 所有库、所有表的查询权限。申请单落库的 scope 因此固定为 '*'。
--
-- 为什么存量的库级授权也要一并提升，而不是只对新申请生效：
--   grant_record 是「这个用户在这个数据源上能查什么」的唯一事实，
--   若只改新记录，同一批人在申请页看到的是「可申请整个数据源」，
--   手里的授权却是某个库，两个口径并存。而拆库拆表的细粒度授权
--   在平台上从来没有对应的维护入口（申请页本来就没有选表，
--   datasource.apply_scopes 也在 0007 里废弃了），留着只会
--   造成「已授权但查不了另一个库」的困惑，且没有任何人依赖它。
--
-- 影响面：所有未撤销、未过期的授权被放宽到整个数据源。
-- 这是有意的决定——授权本来就已经通过申请与审批确认过一次，
-- 放宽的是同一次审批的范围，不需要重新走流程。
-- 已撤销（revoked_at 非空）和已过期的不动：它们本来就不再生效，
-- 改它们没有意义，还会让历史审计记录与当时的实际权限对不上。
--
-- 幂等脚本，可重复执行。

UPDATE grant_record
   SET scope = '*'
 WHERE scope <> '*'
   AND revoked_at IS NULL
   AND expires_at > now();

-- 申请单同理，但只改待审批的：已通过 / 已驳回 / 已撤销的单据是历史记录，
-- 同一个用户在同一数据源上的新授权已由上面的 grant_record 更新覆盖，
-- 改动历史单据只会破坏「当时批的是哪个范围」的留痕。
UPDATE grant_request
   SET scope = '*'
 WHERE scope <> '*'
   AND status = 'pending';

COMMENT ON COLUMN grant_record.scope IS
    '授权范围：* 表示整个数据源（所有库与表）；<库>:* 是改口径前的库级授权，鉴权仍兼容。';
COMMENT ON COLUMN grant_request.scope IS
    '申请范围：申请粒度是数据源，落库固定为 *。';
